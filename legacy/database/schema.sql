CREATE TABLE Tenants (
    TenantId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantCode NVARCHAR(50) NOT NULL UNIQUE,
    TenantName NVARCHAR(200) NOT NULL,
    DomainName NVARCHAR(200) NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    ThemeConfig NVARCHAR(MAX) NULL,
    ModuleAccess NVARCHAR(MAX) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NULL
);

CREATE TABLE Users (
    UserId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    Username NVARCHAR(100) NOT NULL,
    FullName NVARCHAR(200) NOT NULL,
    Email NVARCHAR(200) NULL,
    PasswordHash NVARCHAR(255) NOT NULL,
    RoleName NVARCHAR(50) NOT NULL DEFAULT 'ADMIN',
    IsActive BIT NOT NULL DEFAULT 1,
    LastLoginAt DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NULL,
    CONSTRAINT FK_Users_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE TABLE Roles (
    RoleId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    RoleName NVARCHAR(100) NOT NULL,
    Permissions NVARCHAR(MAX) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Roles_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE TABLE Configurations (
    ConfigId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    ConfigKey NVARCHAR(200) NOT NULL,
    ConfigValue NVARCHAR(MAX) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NULL,
    CONSTRAINT FK_Configurations_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE TABLE AuditLogs (
    LogId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    UserId UNIQUEIDENTIFIER NULL,
    ActionType NVARCHAR(100) NOT NULL,
    ActionDetail NVARCHAR(MAX) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_AuditLogs_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE TABLE Orders (
    OrderId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    OrderCode NVARCHAR(100) NOT NULL,
    CustomerName NVARCHAR(200) NULL,
    OrderStatus NVARCHAR(50) NOT NULL DEFAULT 'PENDING',
    TotalAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NULL,
    CONSTRAINT FK_Orders_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE TABLE Products (
    ProductId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    TenantId UNIQUEIDENTIFIER NOT NULL,
    ProductCode NVARCHAR(100) NOT NULL,
    ProductName NVARCHAR(200) NOT NULL,
    Price DECIMAL(18,2) NOT NULL DEFAULT 0,
    StockQty INT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NULL,
    CONSTRAINT FK_Products_Tenants FOREIGN KEY (TenantId) REFERENCES Tenants(TenantId)
);

CREATE INDEX IX_Users_TenantId ON Users(TenantId);
CREATE INDEX IX_Roles_TenantId ON Roles(TenantId);
CREATE INDEX IX_Configurations_TenantId ON Configurations(TenantId);
CREATE INDEX IX_AuditLogs_TenantId ON AuditLogs(TenantId);
CREATE INDEX IX_Orders_TenantId ON Orders(TenantId);
CREATE INDEX IX_Products_TenantId ON Products(TenantId);
